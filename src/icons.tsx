/// The Lucide icon drawn for an SF Symbol name.
export function iconFor(symbol: string): IconComponent {
  let name = symbol;
  for (;;) {
    const icon = SYMBOLS[name];
    if (icon) return icon;
    const dot = name.lastIndexOf(".");
    if (dot === -1) return L.CircleDot;
    name = name.slice(0, dot);
  }
}

export function Icon({ name, size = 16, className, style, strokeWidth }: {
  name: string;
  size?: number;
  className?: string;
  style?: CSSProperties;
  strokeWidth?: number;
}) {
  const Component = iconFor(name);
  return <Component size={size} className={className} style={style} strokeWidth={strokeWidth ?? 1.9} aria-hidden />;
}
